const MESSAGES: Record<CrmLocale, Record<CrmMessageKey, string>> = { fr, en };

type Vars = Record<string, string | number>;

function interpolate(text: string, vars?: Vars): string {
  if (!vars) return text;

  return text.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}

export function t(key: CrmMessageKey, vars?: Vars): string {
  return interpolate(MESSAGES[crmLocale][key] ?? fr[key], vars);
}

/** Texte au singulier ou au pluriel ; en français, 0 et 1 prennent le singulier. */
export function tp(base: 'clients' | 'runs' | 'errors' | 'steps', count: number, vars?: Vars): string {
  const singular = crmLocale === 'fr' ? count <= 1 : count === 1;
  const key = `${base}.${singular ? 'one' : 'other'}` as CrmMessageKey;

  return t(key, { count: formatNumber(count), ...vars });
}

/** Clé dynamique (champ, événement…) : undefined si elle n'existe pas dans le dictionnaire. */
export function tMaybe(key: string, vars?: Vars): string | undefined {
  return key in fr ? t(key as CrmMessageKey, vars) : undefined;
}

const intlLocale = crmLocale === 'en' ? 'en-GB' : 'fr-FR';

export function formatNumber(value?: number | null): string {
  return (value ?? 0).toLocaleString(intlLocale);
}

export function formatDateTime(value?: string | Date | null): string {
  if (!value) return '—';

  return new Date(value).toLocaleString(intlLocale, { dateStyle: 'medium', timeStyle: 'short' });
}

export function formatDay(value?: string | Date | null): string {
  if (!value) return '—';

  return new Date(value).toLocaleDateString(intlLocale, { dateStyle: 'medium' });
}

export function formatList(items: string[]): string {
  if (items.length <= 1) return items.join('');

  return `${items.slice(0, -1).join(', ')} ${t('schedule.and')} ${items[items.length - 1]}`;
}
